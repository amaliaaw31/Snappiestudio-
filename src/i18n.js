let lang = 'id';
try {
  const saved = localStorage.getItem('snappie-lang');
  if (saved && translations[saved]) lang = saved;
} catch (e) { /* storage tidak tersedia */ }

export function getLang() { return lang; }

export function setLang(code) {
  if (!translations[code]) return;
  lang = code;
  try { localStorage.setItem('snappie-lang', code); } catch (e) { /* abaikan */ }
}

export function t(key, values = {}) {
  const cur = translations[lang];
  const message = cur?.[key] ?? translations.en[key] ?? key;
  return message.replace(/\{(\w+)\}/g, (token, name) => values[name] ?? token);
}

export function applyI18n(root = document) {
  document.documentElement.lang = lang;
  document.documentElement.dir = (lang === 'ar') ? 'rtl' : 'ltr';
  document.title = t('page.title');
  root.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-html]').forEach(el => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  root.querySelectorAll('[data-i18n-ph]').forEach(el => {
    el.setAttribute('placeholder', t(el.dataset.i18nPh));
  });
  root.querySelectorAll('[data-i18n-aria]').forEach(el => {
    el.setAttribute('aria-label', t(el.dataset.i18nAria));
  });
  root.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.setAttribute('title', t(el.dataset.i18nTitle));
  });
}
